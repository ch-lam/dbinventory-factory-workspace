-- ============================================================
-- ref_nis2_domain  (the reading grid the RSSI and the DPO use)
-- ------------------------------------------------------------
-- The scoring domains (SECURITY, BACKUP, CAPACITY, LIFECYCLE) say where a rule
-- lives inside this tool. They say nothing to someone holding the directive:
-- NIS2 article 21(2) names risk-management measures, and SECURITY alone spans
-- five of them at once.
--
-- So this is a SECOND axis over the same rules, never a replacement. Nothing
-- here feeds fact_scoring, ref_scoring_weight or pkg_dbinv_scoring: the score
-- keeps its own vocabulary, and this one exists to be read.
--
-- ONE domain per rule, deliberately. A rule counted in two measures would make
-- every count on the instance and database cards wrong, and a widget that
-- double-counts is worse than no widget. The day a rule genuinely serves two
-- measures, it is the RULE that gets split, not this mapping that gets widened.
--
-- Only the measures a database can attest BY ITSELF are listed. Supply chain
-- security (d) and staff training (g) are real obligations that no collect of
-- ours can evidence; leaving them out is more honest than showing blocks this
-- tool will never be able to fill.
-- ============================================================
create table ref_nis2_domain (
   nis2_domain_code varchar2(20 char) not null,
   display_order    number(2) not null,
   title            varchar2(100 char) not null,
   article_ref      varchar2(20 char) not null,
   description      varchar2(1000 char),
   constraint ref_nis2_domain_pk primary key ( nis2_domain_code ),
   -- the cards are laid out left to right by this column; two domains sharing a
   -- position would make the band order depend on the optimiser
   constraint ref_nis2_domain_uk unique ( display_order )
);

comment on table ref_nis2_domain is 'Risk-management measures of NIS2 article 21(2), restricted to those a database can attest; a second reading axis over ref_control_rule, with no effect on scoring.';
comment on column ref_nis2_domain.nis2_domain_code is 'Unique code of the domain.';
