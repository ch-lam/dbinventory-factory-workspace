-- ============================================================
-- ref_application_entity  (the attachment to the inventory)
-- ------------------------------------------------------------
-- Polymorphic, exactly like ref_exception: entity_type + entity_id, no hard FK,
-- resolved through v_entity_ancestry.
--
-- Why not a plain application-to-database junction: attaching an INSTANCE covers
-- its databases without listing them. With 97 instances against 514 databases,
-- that is the difference between a data-entry effort that happens and one that
-- never does -- while keeping the fine grain available where an instance is
-- genuinely shared between applications.
--
-- Many-to-many in both directions on purpose. One application spans its
-- production, test and development databases; one shared database serves several
-- applications. A column on dim_database could express neither, and dim_database
-- is written by the ETL, so a hand-entered column there would be overwritten by
-- the next load.
-- ============================================================
create table ref_application_entity (
   app_entity_id  number generated by default on null as identity,
   application_id number not null,
   entity_type    varchar2(20 char) not null,
   entity_id      number not null,
   note           varchar2(400 char),
   active         number(1) default 1 not null,
   created_by     varchar2(100 char) default on null nvl(sys_context('APEX$SESSION','APP_USER'), user) not null,
   created_date   date default on null sysdate not null,
   constraint ref_app_ent_pk primary key ( app_entity_id ),
   constraint ref_app_ent_uk unique ( application_id, entity_type, entity_id ),
   constraint ref_app_ent_app_fk foreign key ( application_id )
      references ref_application ( application_id ),
   constraint ref_app_ent_type_ck check ( entity_type in ( 'HOST', 'INSTANCE', 'DATABASE' ) ),
   constraint ref_app_ent_active_ck check ( active in ( 0, 1 ) )
);

comment on table ref_application_entity is 'Attachment of an application to the inventory, at host, instance or database level; an attachment cascades down to everything beneath it.';
