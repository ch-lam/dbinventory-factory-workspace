-- ============================================================
-- ref_application_event  (append-only journal)
-- ------------------------------------------------------------
-- Same reasoning as ref_exception_event: the registry keeps only
-- updated_by/updated_date, so each change erases the previous one and "who
-- removed that document, and when" has no answer. In a document register, that
-- is the question that always gets asked afterwards.
--
-- Append-only is enforced by a trigger rather than left as a convention. An
-- audit trail that can be rewritten proves nothing.
-- ============================================================
create table ref_application_event (
   event_id       number generated by default on null as identity,
   application_id number not null,
   event_type     varchar2(30 char) not null,
   subject_ref    varchar2(200 char),
   event_date     date default on null sysdate not null,
   event_by       varchar2(100 char) default on null nvl(sys_context('APEX$SESSION','APP_USER'), user) not null,
   note           varchar2(1000 char),
   old_value      varchar2(1000 char),
   new_value      varchar2(1000 char),
   constraint ref_app_evt_pk primary key ( event_id ),
   constraint ref_app_evt_app_fk foreign key ( application_id )
      references ref_application ( application_id ),
   constraint ref_app_evt_type_ck check ( event_type in (
      'CREATED', 'UPDATED', 'DEACTIVATED', 'REVIEWED',
      'GROUP_ADDED', 'GROUP_UPDATED', 'GROUP_REMOVED',
      'CONTACT_ADDED', 'CONTACT_UPDATED', 'CONTACT_REMOVED',
      'ENTITY_LINKED', 'ENTITY_UNLINKED',
      'DOCUMENT_ADDED', 'DOCUMENT_REPLACED', 'DOCUMENT_REMOVED', 'DOCUMENT_REVIEWED',
      'SOURCE_ADDED', 'SOURCE_REMOVED' ) )
);

