   active          number(1) default 1 not null,
   created_by      varchar2(100 char) default on null nvl(sys_context('APEX$SESSION','APP_USER'), user) not null,
   created_date    date default on null sysdate not null,
   updated_by      varchar2(100 char),
   updated_date    date,
   constraint ref_app_grp_pk primary key ( group_id ),
   constraint ref_app_grp_uk unique ( application_id, group_type_code, group_name ),
   constraint ref_app_grp_app_fk foreign key ( application_id )
      references ref_application ( application_id ),
   constraint ref_app_grp_type_fk foreign key ( group_type_code )
      references ref_application_group_type ( group_type_code ),
   constraint ref_app_grp_active_ck check ( active in ( 0, 1 ) ),
