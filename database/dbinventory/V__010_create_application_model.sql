-- ============================================================
-- ref_application_document
-- ------------------------------------------------------------
-- A small document register, not an EDM. The need is that everything is
-- scattered today, so what matters is knowing that a document exists, where it
-- is, and whether anyone has looked at it lately.
--
-- Content OR link, and both together are allowed: some documents can be stored
-- here, some can only be pointed at because they live in a system of record.
-- What is refused is NEITHER -- an entry with no content and no URL is the exact
-- failure mode of a document register, an inventory of documents nobody can
-- open.
-- ============================================================
create table ref_application_document (
   document_id      number generated by default on null as identity,
   application_id   number not null,
   doc_kind         varchar2(20 char) default 'OTHER' not null,
   title            varchar2(400 char) not null,
   description      varchar2(2000 char),
   external_url     varchar2(2000 char),
   file_name        varchar2(400 char),
   mime_type        varchar2(200 char),
   file_size        number,
   content          blob,
   checksum_sha256  varchar2(64 char),
   review_due_date  date,
   last_review_date date,
   last_review_by   varchar2(100 char),
   active           number(1) default 1 not null,
   uploaded_by      varchar2(100 char) default on null nvl(sys_context('APEX$SESSION','APP_USER'), user) not null,
   uploaded_date    date default on null sysdate not null,
   updated_by       varchar2(100 char),
   updated_date     date,
   constraint ref_app_doc_pk primary key ( document_id ),
   constraint ref_app_doc_app_fk foreign key ( application_id )
      references ref_application ( application_id ),
   constraint ref_app_doc_kind_ck check ( doc_kind in (
      'PROCEDURE', 'SCRIPT', 'DIAGRAM', 'CONTRACT', 'MAIL', 'MANUAL', 'RUNBOOK', 'OTHER' ) ),
   constraint ref_app_doc_active_ck check ( active in ( 0, 1 ) ),
   -- The guard against a register of documents nobody can open.
   constraint ref_app_doc_body_ck check ( content is not null or external_url is not null ),
   -- A stored file with no name cannot be handed back to anyone.
   constraint ref_app_doc_name_ck check ( content is null or file_name is not null )
) lob ( content ) store as securefile;

