-- ============================================================
-- ref_application_group
-- ------------------------------------------------------------
-- The reachability constraint is the point of this table. A contact registry
-- whose entries cannot reach anybody is worse than no registry, because you
-- believe you have one. A group with no email, no directory group and no
-- external reference is refused outright rather than stored and found useless on
-- the day somebody needs it.
-- ============================================================
create table ref_application_group (
   group_id        number generated by default on null as identity,
   application_id  number not null,
   group_type_code varchar2(20 char) not null,
   group_name      varchar2(200 char) not null,
   contact_email   varchar2(400 char),
